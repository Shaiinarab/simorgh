// ── Knowledge API: validation and namespace rules, shared by both hosts ───────
//
// C2 exposes four operations — index, get, search, delete — over the `RetrievalPort`
// from C1. The route bodies are deliberately thin because the rules that matter are
// not host-specific:
//
//   * a namespace is a **label** the caller chooses, and the host prefixes it with the
//     authenticated principal before it reaches the adapter. That is what makes
//     cross-principal access structurally impossible rather than a filter someone
//     remembered to apply (EPIC-C2 acceptance, A3 ownership).
//   * an id is caller-chosen and unique per namespace; a missing id is generated by the
//     host, because `phoenix-core` must not reach for a `crypto` global.
//   * text is bounded and non-empty, and a body over the cap is a 413, never a silently
//     truncated document. A truncated document is a wrong answer that looks complete.
//
// Everything here is pure over its input and throws `RequestValidationError`, which both
// hosts already render as a stable JSON error. No `node:` import, no `cloudflare:` import,
// no runtime global.

import type { RetrievalDocument, RetrievalHit, RetrievalQuery } from "./ports.ts";
import { RequestValidationError } from "./security.ts";

/** A namespace label: letters, digits, `:`, `_`, `-`, 1–64 chars. */
export const KNOWLEDGE_NAMESPACE_RE = /^[A-Za-z0-9:_-]{1,64}$/;

/** A document id: the same alphabet as a namespace, up to 128 chars. */
export const KNOWLEDGE_ID_RE = /^[A-Za-z0-9:_-]{1,128}$/;

/** The largest document body accepted, in characters. */
export const MAX_KNOWLEDGE_TEXT_CHARS = 50_000;

/** The largest request body accepted, in characters. */
export const MAX_KNOWLEDGE_BODY_CHARS = 100_000;

/** The largest number of hits a search may return. */
export const MAX_KNOWLEDGE_LIMIT = 100;

/** A metadata value, as the retrieval row can store it. */
export type KnowledgeMetadataValue = string | number | boolean | null;

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

/** Keep only JSON-serialisable scalar metadata; drop everything else. */
function sanitizeMetadata(value: unknown): Record<string, KnowledgeMetadataValue> | undefined {
  if (!isRecord(value)) return undefined;
  const out: Record<string, KnowledgeMetadataValue> = {};
  for (const [key, entry] of Object.entries(value)) {
    if (entry === null || typeof entry === "string" || typeof entry === "boolean") {
      out[key] = entry;
    } else if (typeof entry === "number" && Number.isFinite(entry)) {
      out[key] = entry;
    }
  }
  return Object.keys(out).length === 0 ? undefined : out;
}

export function validateKnowledgeNamespace(label: string): void {
  if (!KNOWLEDGE_NAMESPACE_RE.test(label)) {
    throw new RequestValidationError(
      400,
      "INVALID_NAMESPACE",
      "namespace must be 1–64 characters of letters, digits, ':', '_' or '-'."
    );
  }
}

export function validateKnowledgeId(id: string): void {
  if (!KNOWLEDGE_ID_RE.test(id)) {
    throw new RequestValidationError(
      400,
      "INVALID_ID",
      "id must be 1–128 characters of letters, digits, ':', '_' or '-'."
    );
  }
}

/** Read and validate a JSON object from a request body. */
function parseObject(raw: string): Record<string, unknown> {
  if (raw.length > MAX_KNOWLEDGE_BODY_CHARS) {
    throw new RequestValidationError(
      413,
      "request_too_large",
      "Knowledge request body exceeds " + MAX_KNOWLEDGE_BODY_CHARS + " characters."
    );
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new RequestValidationError(400, "INVALID_JSON", "Request body must be valid JSON.");
  }
  if (!isRecord(parsed)) {
    throw new RequestValidationError(400, "INVALID_BODY", "Request body must be a JSON object.");
  }
  return parsed;
}

/**
 * Parse `POST /knowledge`.
 *
 * `generatedId` is supplied by the host (a UUID) so the engine never reaches for a
 * `crypto` global. When the body carries an id, it wins — a caller re-indexing a document
 * expects the same id to replace it.
 */
export function parseKnowledgeIndex(raw: string, generatedId: string): RetrievalDocument {
  const body = parseObject(raw);

  const namespace = typeof body.namespace === "string" ? body.namespace : "";
  validateKnowledgeNamespace(namespace);

  const text = typeof body.text === "string" ? body.text : "";
  if (text.trim() === "") {
    throw new RequestValidationError(400, "EMPTY_TEXT", "text must not be empty.");
  }
  if (text.length > MAX_KNOWLEDGE_TEXT_CHARS) {
    throw new RequestValidationError(
      413,
      "text_too_large",
      "text exceeds " + MAX_KNOWLEDGE_TEXT_CHARS + " characters."
    );
  }

  const id = typeof body.id === "string" && body.id !== "" ? body.id : generatedId;
  validateKnowledgeId(id);

  return {
    id,
    namespace,
    title: typeof body.title === "string" ? body.title : undefined,
    text,
    metadata: sanitizeMetadata(body.metadata),
    timestamp:
      typeof body.timestamp === "number" && Number.isFinite(body.timestamp)
        ? body.timestamp
        : undefined,
  };
}

/** Parse `POST /knowledge/search`. */
export function parseKnowledgeSearch(raw: string): RetrievalQuery {
  const body = parseObject(raw);

  const namespace = typeof body.namespace === "string" ? body.namespace : "";
  validateKnowledgeNamespace(namespace);

  const text = typeof body.text === "string" ? body.text : "";
  if (text.trim() === "") {
    throw new RequestValidationError(400, "EMPTY_QUERY", "text must not be empty.");
  }

  const limit =
    typeof body.limit === "number" && Number.isFinite(body.limit)
      ? Math.max(1, Math.min(Math.floor(body.limit), MAX_KNOWLEDGE_LIMIT))
      : 10;

  return { namespace, text, limit };
}

/** Parse `GET|DELETE /knowledge/:id?namespace=...`. */
export function parseKnowledgeTarget(id: string, namespace: string): void {
  validateKnowledgeId(id);
  validateKnowledgeNamespace(namespace);
}

/**
 * The stored namespace for a principal's label.
 *
 * The prefix is the credential's subject, so a caller cannot name another principal's
 * namespace: the label they send is always under their own prefix. C3 will add per-agent
 * namespaces on top of this; the isolation rule is already structural.
 */
export function knowledgeNamespaceFor(subject: string, label: string): string {
  return subject + "::" + label;
}

/** Strip the principal prefix so a hit reports the label the caller sent. */
export function publicKnowledgeNamespace(subject: string, namespace: string): string {
  const prefix = subject + "::";
  return namespace.startsWith(prefix) ? namespace.slice(prefix.length) : namespace;
}

/** Return a hit with the caller-facing namespace and nothing else changed. */
export function toPublicKnowledgeHit(subject: string, hit: RetrievalHit): RetrievalHit {
  return { ...hit, namespace: publicKnowledgeNamespace(subject, hit.namespace) };
}